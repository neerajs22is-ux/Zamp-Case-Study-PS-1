"""Append-Only Audit Log API & Audited Export.

Enforces:
1. Purely append-only query access (zero edit/delete endpoints).
2. Filterable by invoice, actor, action, date, and correlation ID.
3. CSV export restricted to authorized roles, with the export itself committed as an audit event.
"""

from __future__ import annotations

import csv
import datetime
import io
import uuid
from typing import Any, Dict, List, Optional
from fastapi import APIRouter, Depends, Query, Response
from sqlalchemy import select
from sqlalchemy.orm import Session

from backend.core.auth import AuthenticatedUser, UserRole, require_active_membership, require_role
from backend.core.database import get_db
from backend.models.domain import AuditEvent

router = APIRouter(prefix="/audit", tags=["Audit Log & Compliance"])


@router.get("")
def list_audit_events(
    invoice_id: Optional[str] = Query(None),
    actor_id: Optional[str] = Query(None),
    action: Optional[str] = Query(None),
    correlation_id: Optional[str] = Query(None),
    limit: int = Query(50, ge=1, le=200),
    current_user: AuthenticatedUser = Depends(require_active_membership),
    db: Optional[Session] = Depends(get_db),
) -> Dict[str, Any]:
    """Returns append-only audit trail filtered by query parameters."""
    if db is None:
        return {
            "total_count": 0,
            "items": [],
            "message": "Database not connected. No audit logs available.",
        }

    stmt = select(AuditEvent).where(AuditEvent.org_id == current_user.org_id)

    if invoice_id:
        stmt = stmt.where(AuditEvent.invoice_id == invoice_id)
    if actor_id:
        stmt = stmt.where(AuditEvent.actor_id == actor_id)
    if action:
        stmt = stmt.where(AuditEvent.action == action)
    if correlation_id:
        stmt = stmt.where(AuditEvent.correlation_id == correlation_id)

    events = db.scalars(stmt.order_by(AuditEvent.timestamp.desc()).limit(limit)).all()

    items = [
        {
            "id": e.id,
            "invoice_id": e.invoice_id,
            "actor_id": e.actor_id,
            "actor_role": e.actor_role,
            "action": e.action,
            "reason": e.reason,
            "correlation_id": e.correlation_id,
            "before_state": e.before_state,
            "after_state": e.after_state,
            "source_reference": e.source_reference,
            "timestamp": e.timestamp.isoformat() + "Z",
        }
        for e in events
    ]

    return {
        "total_count": len(items),
        "items": items,
    }


@router.get("/export")
def export_audit_csv(
    current_user: AuthenticatedUser = Depends(require_role([UserRole.AUDITOR, UserRole.CONTROLLER, UserRole.SYSTEM_ADMIN])),
    db: Optional[Session] = Depends(get_db),
) -> Response:
    """Exports audit trail as CSV for authorized compliance roles.

    The export action itself is recorded as an immutable AuditEvent.
    """
    if db is None:
        return Response(content="Database not connected", media_type="text/plain", status_code=503)

    events = db.scalars(
        select(AuditEvent).where(AuditEvent.org_id == current_user.org_id).order_by(AuditEvent.timestamp.desc())
    ).all()

    output = io.StringIO()
    writer = csv.writer(output)
    writer.writerow(["Event ID", "Timestamp", "Invoice ID", "Actor ID", "Actor Role", "Action", "Reason", "Correlation ID"])

    for e in events:
        writer.writerow([e.id, e.timestamp.isoformat() + "Z", e.invoice_id or "", e.actor_id, e.actor_role, e.action, e.reason or "", e.correlation_id or ""])

    # Log that export occurred
    export_audit = AuditEvent(
        id=f"evt_{uuid.uuid4().hex[:12]}",
        org_id=current_user.org_id,
        actor_id=current_user.id,
        actor_role=current_user.role.value,
        action="AUDIT_TRAIL_EXPORTED",
        reason=f"CSV compliance export generated by {current_user.email}",
        timestamp=datetime.datetime.utcnow(),
    )
    db.add(export_audit)
    db.commit()

    return Response(
        content=output.getvalue(),
        media_type="text/csv",
        headers={"Content-Disposition": f"attachment; filename=ap_audit_log_{datetime.date.today().isoformat()}.csv"},
    )
